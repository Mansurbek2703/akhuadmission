export function formatAddress(
  country?: string,
  region?: string,
  district?: string,
  street?: string,
): string {
  if (!country) return "";
  if (country !== "uzbekistan") return street || "";
  const parts = [
    "Uzbekistan",
    region || "",
    district || "",
    street || "",
  ].filter(Boolean);
  return parts.join(", ");
}
